"""One original voxel specification for Java flight layer, item and editable Blockbench.
Coordinates: X lateral, Y longitudinal (positive aft), Z above prone pilot.
"""
import base64, json, math, uuid
from pathlib import Path
from PIL import Image, ImageDraw

ROOT=Path(__file__).resolve().parents[1]
ASSETS=ROOT/'src/main/resources/assets/windcraft'
OUT=ROOT/'docs/models'
boxes=[]
def box(name,x,y,z,w,h,d,cloth=False):
    boxes.append((name,x,y,z,w,h,d,cloth))

box('spine',-.6,-23,15.4,1.2,61,1.2)
box('grip',-9,-5.16,6.96,18,1,1)
for x in (-5,5):box('suspension',x-.5,-5.16,7.46,1,1,8.5)

def fan(label,cy,radius,inner,step):
    for x in range(-radius,radius,step):
        for y in range(0,radius,step):
            r=math.hypot(x+step/2,y+step/2)
            if inner<=r<=radius:
                box(label+'_cloth',x,cy+y,15.1,step,step,.55,True)
    # Stepped radial battens are solid voxels and remain attached to the hub.
    for deg in range(0,181,30):
        a=math.radians(deg)
        for r in range(radius):
            box(label+'_rib',math.cos(a)*r-.45,cy+math.sin(a)*r-.45,15.65,.9,.9,.7)
fan('wing',-15,30,11,2)
fan('tail',26,10,3,1)

im=Image.new('RGBA',(128,128));px=im.load()
for y in range(128):
    for x in range(128):
        if y<64:
            c=(116,69,36) if x%7 in (0,1) else (161,103,52)
        else:
            c=(190,65,22) if x%8==0 or y%8==0 else (229,106,32)
        px[x,y]=c+(255,)
tex=ASSETS/'textures/entity/wind_glider.png';im.save(tex)
im.resize((512,512),Image.Resampling.NEAREST).save(OUT/'wind_glider_atlas_preview.png')

lines=['package dev.windcraft.rendering;','',
 'import net.minecraft.client.model.EntityModel;',
 'import net.minecraft.client.model.geom.PartPose;',
 'import net.minecraft.client.model.geom.builders.*;',
 'import net.minecraft.client.renderer.entity.state.AvatarRenderState;',
 '/** Generated by tools/create_fan_glider.py. X span, Y aft, Z above prone pilot. */',
 'public final class GliderModel extends EntityModel<AvatarRenderState> {',
 '    public static final float BAR_Y=-4.66f, BAR_Z=7.46f;',
 '    public GliderModel() { super(createLayer().bakeRoot()); }',
 '    public static LayerDefinition createLayer() {',
 '        var mesh=new MeshDefinition();',
 '        var geometry=CubeListBuilder.create();']
for n,x,y,z,w,h,d,cloth in boxes:
    lines.append('        geometry.texOffs(0,'+str(64 if cloth else 0)+').addBox('+','.join(str(round(v,5))+'f' for v in (x,y,z,w,h,d))+');')
lines+=['        mesh.getRoot().addOrReplaceChild("fan_glider",geometry,PartPose.ZERO);',
 '        return LayerDefinition.create(mesh,128,128);','    }','}']
(ROOT/'src/main/java/dev/windcraft/rendering/GliderModel.java').write_text('\n'.join(lines)+'\n')

# Same voxels, scaled to legal item-model bounds. Thin axis is item Y.
elements=[]
for n,x,y,z,w,h,d,cloth in boxes:
    a=[8+x*.35,3+z*.35,8+y*.35];b=[a[0]+w*.35,a[1]+d*.35,a[2]+h*.35]
    elements.append(dict(name=n,**{'from':a,'to':b},faces={f:dict(texture='#atlas',uv=[0,8 if cloth else 0,1,9 if cloth else 1]) for f in ('up','down','north','south','east','west')}))
model=dict(textures=dict(atlas='windcraft:entity/wind_glider',particle='windcraft:entity/wind_glider'),elements=elements,
 display={'gui':dict(rotation=[75,0,0],translation=[0,0,0],scale=[.7,.7,.7]),
 'firstperson_righthand':dict(rotation=[0,-45,75],translation=[1,-2,0],scale=[.35,.35,.35]),
 'firstperson_lefthand':dict(rotation=[0,45,-75],translation=[-1,-2,0],scale=[.35,.35,.35]),
 'thirdperson_righthand':dict(rotation=[75,0,0],translation=[0,1,0],scale=[.5,.5,.5]),
 'thirdperson_lefthand':dict(rotation=[75,0,0],translation=[0,1,0],scale=[.5,.5,.5])})
(ASSETS/'models/item/wind_glider_fan.json').write_text(json.dumps(model,indent=2))
(ASSETS/'items/wind_glider.json').write_text(json.dumps(dict(model=dict(type='minecraft:model',model='windcraft:item/wind_glider_fan')),indent=2))

def uid(n):return str(uuid.uuid5(uuid.NAMESPACE_URL,'windcraft:fan:'+str(n)))
bb=[]
for i,(n,x,y,z,w,h,d,cloth) in enumerate(boxes):
    u,v=0,64 if cloth else 0
    rects={'east':[u,v+d,u+d,v+d+h],'north':[u+d,v+d,u+d+w,v+d+h],
           'west':[u+d+w,v+d,u+2*d+w,v+d+h],'south':[u+2*d+w,v+d,u+2*d+2*w,v+d+h],
           'up':[u+d,v,u+d+w,v+d],'down':[u+d+w,v+d,u+d+2*w,v]}
    bb.append(dict(name=n,uuid=uid(i),type='cube',box_uv=True,uv_offset=[0,64 if cloth else 0],
       **{'from':[x,24-y-h,z],'to':[x+w,24-y,z+d]},origin=[0,24,0],
       faces={f:dict(texture=0,uv=rects[f]) for f in rects}))
project=dict(meta=dict(format_version='4.10',model_format='modded_entity',box_uv=True),name='WindCraft Fan Glider',
 resolution=dict(width=128,height=128),elements=bb,
 outliner=[dict(name='fan_glider',uuid=uid('root'),origin=[0,24,0],children=[e['uuid'] for e in bb])],
 textures=[dict(name='wind_glider.png',id='0',uuid=uid('texture'),width=128,height=128,
 source='data:image/png;base64,'+base64.b64encode(tex.read_bytes()).decode())])
(OUT/'wind_glider_fan.bbmodel').write_text(json.dumps(project,indent=2))

preview=Image.new('RGB',(512,512),'#eee7da');draw=ImageDraw.Draw(preview)
for n,x,y,z,w,h,d,cloth in sorted(boxes,key=lambda b:b[3]):
    draw.rectangle((256+x*6,165+y*6,256+(x+w)*6,165+(y+h)*6),fill='#df7227' if cloth else '#754925')
preview.save(OUT/'wind_glider_fan_preview.png')
print(f'Generated {len(boxes)} solid voxel segments, Java, item, atlas, Blockbench and plan preview.')
import runpy
runpy.run_path(str(ROOT/'tools/create_glider_colors.py'),run_name='__main__')
